function slugify(value) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

export const products = productEntries.map((product) => ({
  ...product,
  slug: product.slug || slugify(product.title),
  image: product.images[0].src,
  alt: product.images[0].alt,
}));

